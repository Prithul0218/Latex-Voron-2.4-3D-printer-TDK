"""Orca-style Klipper G-code test inputs (synthetic, built to include the constructs Orca emits)."""
import math, random
def f(v):
    s=f"{v:.3f}".rstrip("0").rstrip(".")
    return s[1:] if s.startswith("0.") else s.replace("-0.","-.")
def dogbone(layers=3, seed=1, partial_axis=True):
    random.seed(seed)
    g=["; generated by OrcaSlicer (synthetic test)","EXCLUDE_OBJECT_DEFINE NAME=dogbone_id_0_copy_0 CENTER=175,175",
       "M104 S0","G90","M83","G28","LASER_ARM","SET_VELOCITY_LIMIT ACCEL=3000","G92 E0"]
    h=0.2; w=0.6; epm=0.0569
    # dogbone outline: grips 15 mm long x 10 mm wide at both ends, gauge 30 x 3 mm
    def half_width(xx):                # half width as function of x (0..75)
        if xx<12 or xx>63: return 5.0
        if xx<18: return 5.0-(xx-12)/6*3.5
        if xx>57: return 1.5+(xx-57)/6*3.5
        return 1.5
    X0,Y0=137.5,175.0
    for L in range(layers):
        z=h*(L+1)
        g+=[";LAYER_CHANGE",f";Z:{f(z)}",f";HEIGHT:{f(h)}",f"G1 Z{f(z)} F600","G92 E0",
            "EXCLUDE_OBJECT_START NAME=dogbone_id_0_copy_0",";TYPE:Internal solid infill",f";WIDTH:{w}"]
        ys=[Y0-4.7+i*0.47 for i in range(21)]
        # each Y row: x extent where half_width(x) >= |y-Y0|
        def spans(yy):     # contiguous x-intervals of this row inside the dogbone
            out=[]; cur=None
            for i in range(301):
                inside=half_width(i*0.25)>=abs(yy-Y0)-1e-9
                if inside and cur is None: cur=[i*0.25,i*0.25]
                elif inside: cur[1]=i*0.25
                elif cur is not None: out.append(cur); cur=None
            if cur is not None: out.append(cur)
            return [(X0+a,X0+b) for a,b in out if b-a>0.3]
        rows=[]
        for k,yy in enumerate(ys):
            for a,b in spans(yy): rows.append((k,yy,a,b))
        # Orca prints each region as its own zig-zag: left grip+gauge rows, then right grip rows
        rows.sort(key=lambda r:(r[2]>X0+40 and (r[3]-r[2])<40, r[0]))
        x,y=None,None; first=True
        for k,yy,a,b in rows:
            fwd = (k%2==0)
            s,e=(a,b) if fwd else (b,a)
            if first or abs(s-x)>2.0:          # disconnected -> travel
                g+=[f"G1 Z{f(z+.4)} F600",f"G1 X{f(s)} Y{f(yy)} F12000",f"G1 Z{f(z)} F600"]
                first=False
            else:                               # connector extrusion
                g.append(f"G1 X{f(s)} Y{f(yy)} E{f(epm*math.hypot(s-x,yy-y))}")
            # Orca often splits a line with feature/accel/width changes mid-path
            if random.random()<0.6:
                m=(s+e)/2
                g.append(f"G1 X{f(m)} Y{f(yy)} E{f(epm*abs(m-s))} F300")
                g.append(random.choice(["SET_VELOCITY_LIMIT ACCEL=2500",";WIDTH:0.62","M204 S2000","G1 F240"]))
                g.append(f"G1 X{f(e)} Y{f(yy)} E{f(epm*abs(e-m))} F300")
            else:
                g.append(f"G1 X{f(e)} Y{f(yy)} E{f(epm*abs(e-s))} F300")
            x,y=e,yy
        g.append("EXCLUDE_OBJECT_END NAME=dogbone_id_0_copy_0")
        if partial_axis:   # Orca sometimes emits single-axis travels
            g+=[f"G1 Z{f(z+.4)} F600",f"G1 X{f(X0+40)} F12000",f"G1 Z{f(z)} F600"]
    g+=["LASER_DISARM","G1 Z30 F600"]
    return g
def ladder_like():
    g=["M83","G90","G28","LASER_ARM","G1 Z.6 F600"]
    for k,yy in enumerate([150,151,152,153]):
        a,b=(145,205) if k%2==0 else (205,145)
        g+=[f"G1 X{a} Y{yy} F6000" if k==0 else f"G1 X{a} Y{yy} E.11", "M204 S1000", f"G1 X{b} Y{yy} E7.05 F300"]
    g+=["LASER_DISARM"]
    return g
if __name__=="__main__":
    open("in_dogbone.gcode","w").write("\n".join(dogbone())+"\n")
    open("in_dogbone_seed2.gcode","w").write("\n".join(dogbone(4,seed=7))+"\n")
    open("in_dogbone_plain.gcode","w").write("\n".join(dogbone(2,seed=3,partial_axis=False))+"\n")
    open("in_zigzag_split.gcode","w").write("\n".join(ladder_like())+"\n")
    print("ok")
